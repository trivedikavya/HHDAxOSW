import { SEVERITY_LEVELS, SEVERITY_ORDER } from "../schemas/enums.js";

function countBySeverity(findings) {
  const counts = Object.fromEntries(SEVERITY_LEVELS.map((level) => [level, 0]));
  for (const finding of findings) {
    counts[finding.severity] += 1;
  }
  return counts;
}

function severityHeading(severity) {
  return severity.charAt(0).toUpperCase() + severity.slice(1);
}

/**
 * Generates a Markdown report from a validated ScanResult. This is the
 * single source of truth for report content - the API route and any
 * future export path must call this function rather than re-implementing
 * formatting, so the report always matches what the UI shows.
 *
 * @param {import("../schemas/finding.js").ScanResult} scanResult
 * @returns {string} Markdown document
 */
export function generateMarkdownReport(scanResult) {
  const { repository, findings, completedAt, scanId } = scanResult;
  const counts = countBySeverity(findings);

  const lines = [];
  lines.push(`# RepoMedic AI Report — ${repository.name}`);
  lines.push("");
  lines.push(`- **Scan ID:** ${scanId}`);
  lines.push(`- **Completed at:** ${completedAt}`);
  lines.push(`- **Detected project type:** ${repository.projectType}`);
  lines.push(`- **Files inspected:** ${repository.fileCount}`);
  lines.push(`- **Source:** ${repository.isDemo ? "Bundled demo repository" : "Uploaded archive"}`);
  lines.push("");
  lines.push(
    "> RepoMedic AI inspects repository files without executing any uploaded code. This report reflects deterministic, rule-based checks only."
  );
  lines.push("");

  lines.push("## Summary");
  lines.push("");
  if (findings.length === 0) {
    lines.push(
      "No findings were produced by the current set of deterministic checks. This does not guarantee the repository is free of other issues - it means none of RepoMedic AI's current rules detected a problem."
    );
  } else {
    lines.push("| Severity | Count |");
    lines.push("| --- | --- |");
    for (const level of SEVERITY_LEVELS) {
      if (counts[level] > 0) {
        lines.push(`| ${severityHeading(level)} | ${counts[level]} |`);
      }
    }
  }
  lines.push("");

  if (findings.length > 0) {
    lines.push("## Findings");
    lines.push("");

    const sorted = [...findings].sort(
      (a, b) => SEVERITY_ORDER[a.severity] - SEVERITY_ORDER[b.severity]
    );

    for (const finding of sorted) {
      lines.push(`### ${finding.title}`);
      lines.push("");
      lines.push(`- **ID:** \`${finding.id}\``);
      lines.push(`- **Rule:** \`${finding.ruleId}\``);
      lines.push(`- **Severity:** ${severityHeading(finding.severity)}`);
      lines.push(`- **Category:** ${finding.category}`);
      lines.push(
        `- **Affected file:** ${finding.affectedFile ? `\`${finding.affectedFile}\`` : "Not reliably determined"}`
      );
      lines.push(`- **Verified by:** ${finding.verifiedBy}`);
      lines.push("");
      lines.push(finding.message);
      lines.push("");
      lines.push("**Evidence:**");
      lines.push("");
      for (const evidence of finding.evidence) {
        lines.push(`- \`${evidence.file}\`: ${evidence.description}`);
      }
      lines.push("");
      lines.push("**Recommendation:**");
      lines.push("");
      lines.push(finding.recommendation);
      lines.push("");
    }
  }

  lines.push("---");
  lines.push(
    "_Generated by RepoMedic AI (Phase 1 - deterministic checks only, no AI model involved)._"
  );
  lines.push("");

  return lines.join("\n");
}
