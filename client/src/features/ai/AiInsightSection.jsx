import { BrainCircuit, Loader2, Copy, AlertCircle } from "lucide-react";
import { SeverityBadge } from "../../components/SeverityBadge.jsx";
import { useToast } from "../../components/Toast.jsx";

/**
 * Renders the AI-generated portion of a finding's detail view. Always
 * visually distinct from the deterministic content above it (purple
 * accent border/background, brain-circuit icon, explicit "AI-generated
 * suggestion" label) so a reader can never mistake an AI suggestion for
 * a verified, deterministic fact.
 */
export function AiInsightSection({ aiStatus, aiInsight, aiMessage }) {
  const { showToast } = useToast();

  if (aiStatus === "idle") return null;

  if (aiStatus === "loading") {
    return (
      <div className="flex items-center gap-2 rounded-lg border border-accent/20 bg-accent/5 px-3 py-2.5 text-sm text-ink-soft">
        <Loader2 size={14} className="animate-spin text-accent" aria-hidden="true" />
        Generating AI explanation…
      </div>
    );
  }

  if (aiStatus === "unavailable" || aiStatus === "error") {
    return (
      <div className="flex items-start gap-2 rounded-lg border border-border bg-raised px-3 py-2.5 text-sm text-ink-soft">
        <AlertCircle size={14} className="mt-0.5 shrink-0 text-ink-faint" aria-hidden="true" />
        <span>AI explanation unavailable{aiMessage ? `: ${aiMessage}` : "."}</span>
      </div>
    );
  }

  // aiStatus === "ready"
  if (!aiInsight) {
    return (
      <p className="text-sm text-ink-faint">
        No AI suggestion was generated for this finding.
      </p>
    );
  }

  const handleCopyIssueDraft = async () => {
    const { title, body } = aiInsight.issueDraft;
    const text = `${title}\n\n${body}`;
    try {
      await navigator.clipboard.writeText(text);
      showToast("Issue draft copied to clipboard.");
    } catch {
      showToast("Could not copy to clipboard.", "error");
    }
  };

  return (
    <div className="rounded-lg border border-accent/30 bg-accent/5 p-4">
      <div className="flex flex-wrap items-center justify-between gap-2">
        <span className="inline-flex items-center gap-1.5 text-xs font-semibold uppercase tracking-wide text-accent">
          <BrainCircuit size={14} aria-hidden="true" />
          AI-generated suggestion
        </span>
        <SeverityBadge severity={aiInsight.priority} />
      </div>

      <p className="mt-3 text-sm text-ink">{aiInsight.explanation}</p>

      <div className="mt-3 grid gap-4 sm:grid-cols-2">
        <div>
          <h5 className="text-xs font-semibold uppercase tracking-wide text-ink-faint">
            Remediation
          </h5>
          <ul className="mt-1.5 list-inside list-disc space-y-1 text-sm text-ink-soft">
            {aiInsight.remediationSteps.map((step, index) => (
              <li key={index}>{step}</li>
            ))}
          </ul>
        </div>
        <div>
          <h5 className="text-xs font-semibold uppercase tracking-wide text-ink-faint">
            Verification
          </h5>
          <ul className="mt-1.5 list-inside list-disc space-y-1 text-sm text-ink-soft">
            {aiInsight.verificationSteps.map((step, index) => (
              <li key={index}>{step}</li>
            ))}
          </ul>
        </div>
      </div>

      {aiInsight.issueDraft ? (
        <div className="mt-4 rounded-lg border border-border bg-card p-3">
          <div className="flex items-center justify-between gap-2">
            <h5 className="text-xs font-semibold uppercase tracking-wide text-ink-faint">
              Contributor-ready issue draft
            </h5>
            <button
              type="button"
              onClick={handleCopyIssueDraft}
              className="inline-flex items-center gap-1 rounded-md border border-border px-2 py-1 text-xs font-medium text-ink-soft hover:bg-raised hover:text-ink"
            >
              <Copy size={12} aria-hidden="true" />
              Copy
            </button>
          </div>
          <p className="mt-2 text-sm font-medium text-ink">{aiInsight.issueDraft.title}</p>
          <p className="mt-1 whitespace-pre-wrap text-sm text-ink-soft">
            {aiInsight.issueDraft.body}
          </p>
        </div>
      ) : null}

      <p className="mt-3 text-xs text-ink-faint">
        This explanation was generated by a local AI model and is a suggestion, not a
        verified fact. It does not replace the deterministic finding above.
      </p>
    </div>
  );
}
